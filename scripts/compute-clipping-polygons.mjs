function toPct(poly, box) {
  return poly.map(([x, y]) => {
    const px = Math.max(0, Math.min(100, (x - box.minX) / box.W * 100)).toFixed(2);
    const py = Math.max(0, Math.min(100, (y - box.minY) / box.H * 100)).toFixed(2);
    return `${px}% ${py}%`;
  }).join(', ');
}

